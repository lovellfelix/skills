#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');
const yaml = require('js-yaml');

const normalize = require('./normalize');

const ROOT = process.cwd();

// allow overriding the KB root directory via --root PATH or --root=PATH
function getArg(name) {
  for (let i = 2; i < process.argv.length; i++) {
    const a = process.argv[i];
    if (a === name && process.argv[i+1]) return process.argv[i+1];
    if (a.startsWith(name + '=')) return a.split('=')[1];
  }
  return null;
}
const ROOT_DIR = getArg('--root') ? path.resolve(getArg('--root')) : ROOT;
const OUT = path.join(ROOT_DIR, 'backlinks');
const IGNORE = ['.git', 'node_modules', 'dist', 'build', '.github', '.mcp', 'backlinks', 'examples', 'docs', 'tests', '.githooks', 'SKILL.md', 'KB_OWNERS.md'];

function walk(dir) {
  const results = [];
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      if (IGNORE.includes(name)) continue;
      results.push(...walk(full));
    } else if (stat.isFile() && name.endsWith('.md')) {
      // skip known non-KB packaging or docs files
      if (IGNORE.includes(name)) continue;
      results.push(full);
    }
  }
  return results;
}

function parseFrontmatter(content) {
  try {
    const parsed = matter(content, { engines: { yaml: s => yaml.load(s) } });
    return { body: parsed.content, frontmatter: parsed.data };
  } catch (e) {
    return { body: content };
  }
}

function slugFromPath(p) {
  return path.relative(ROOT_DIR, p).replace(/\\/g, '/');
}

function extractWikilinks(text) {
  const links = [];
  const wiki = text.match(/\[\[([^\]]+)\]\]/g);
  if (wiki) {
    for (const w of wiki) {
      const m = w.match(/\[\[([^\]]+)\]\]/);
      if (m) links.push(m[1].trim());
    }
  }
  return links;
}

function extractRelativeLinks(text) {
  const re = /\[[^\]]+\]\(([^)]+\.md)\)/g;
  const out = [];
  let m;
  while ((m = re.exec(text)) !== null) {
    out.push(m[1]);
  }
  return out;
}

const files = walk(ROOT_DIR);
const titleMap = new Map();
const nameToFiles = new Map();

// map titles (from frontmatter) and file paths, also build name->file(s) map including aliases
for (const f of files) {
  const raw = fs.readFileSync(f,'utf8');
  try {
    const parsed = matter(raw, { engines: { yaml: s => yaml.load(s) } });
    const title = parsed.data && parsed.data.title ? parsed.data.title : path.basename(f);
    const slug = slugFromPath(f);
    titleMap.set(f, {title: title, slug: slug});
    // add normalized title
    const tnorm = normalize(title);
    if (tnorm) {
      if (!nameToFiles.has(tnorm)) nameToFiles.set(tnorm, []);
      nameToFiles.get(tnorm).push({path:f, slug, title});
    }
    // add aliases
    const aliases = parsed.data && (parsed.data.aliases || parsed.data.alias) || [];
    if (typeof aliases === 'string') {
      const an = normalize(aliases);
      if (an) {
        if (!nameToFiles.has(an)) nameToFiles.set(an, []);
        nameToFiles.get(an).push({path:f, slug, title});
      }
    } else if (Array.isArray(aliases)) {
      for (const a of aliases) {
        const an = normalize(a);
        if (!an) continue;
        if (!nameToFiles.has(an)) nameToFiles.set(an, []);
        nameToFiles.get(an).push({path:f, slug, title});
      }
    }
  } catch (e) {
    const slug = slugFromPath(f);
    titleMap.set(f, {title: path.basename(f), slug});
    const tnorm = normalize(path.basename(f));
    if (tnorm) {
      if (!nameToFiles.has(tnorm)) nameToFiles.set(tnorm, []);
      nameToFiles.get(tnorm).push({path:f, slug, title: path.basename(f)});
    }
  }
}

const backlinks = {};
for (const f of files) {
  const raw = fs.readFileSync(f,'utf8');
  const parsed = parseFrontmatter(raw);
  const body = parsed.body;
  const wiki = extractWikilinks(body);
  const rel = extractRelativeLinks(body);
  const src = slugFromPath(f);
  for (const w of wiki) {
    const wn = normalize(w);
    if (!wn) continue;
    const matches = nameToFiles.get(wn) || [];
    for (const m of matches) {
      backlinks[m.slug] = backlinks[m.slug] || [];
      backlinks[m.slug].push(src);
    }
  }
  for (const r of rel) {
    const target = path.join(path.dirname(f), r);
    const norm = path.relative(ROOT_DIR, target).replace(/\\/g, '/');
    backlinks[norm] = backlinks[norm] || [];
    backlinks[norm].push(src);
  }
}

if (!fs.existsSync(OUT)) fs.mkdirSync(OUT);
fs.writeFileSync(path.join(OUT,'index.json'), JSON.stringify(backlinks,null,2));

// write a human readable summary
const lines = ['# Backlinks index', 'Generated by scripts/generate-backlinks.js', ''];
for (const [target, sources] of Object.entries(backlinks)) {
  lines.push(`## ${target}`);
  for (const s of sources) lines.push(` - ${s}`);
  lines.push('');
}
fs.writeFileSync(path.join(OUT,'BACKLINKS.md'), lines.join('\n'));
console.log('Backlinks generated at', OUT);
process.exit(0);
